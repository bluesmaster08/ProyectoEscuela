        // -->>DE CLIENTE A SERVIDOR (OUTPUT)
        // Método para abrir una conexión con el servidor a través de sockets.
        private void abrirConexionConElServidor() {
                String msg = null;
                String ip = null;
                int puerto = 0;
                try {
                        ip = SERVER_IP;
                        puerto = SERVER_PORT;
                        socket = new Socket(ip, puerto);
                        output = new DataOutputStream(socket.getOutputStream());
                        input = new DataInputStream(socket.getInputStream());
                } catch (IOException e) {
                        msg = "Error al intentar abrir la conexión con el servidor.\n"
                                        + "Ip: " + ip + "\nPuerto: " + puerto
                                        + "\n\nProbablemente el servidor no está disponible o el puerto está en uso.";
                        JOptionPane.showMessageDialog(this, msg, "Error", JOptionPane.ERROR_MESSAGE);
                        e.printStackTrace();
                }
        }

        // Método para enviar solictudes de estudiantes
        private void enviarDatos() {
                try {
                        // Recuperar datos del formulario
                        String nombre = txtNombre.getText();
                        String matricula = txtMatricula.getText();
                        // Validar que los campos de nombre y matrícula no estén vacíos
                        if (nombre.isEmpty() || matricula.isEmpty()) {
                                JOptionPane.showMessageDialog(this, "Por favor, ingrese el nombre y la matrícula.",
                                                "Error",
                                                JOptionPane.ERROR_MESSAGE);
                                return; // Salir del método si la validación falla
                        }
                        // Recupera los datos del formulario cliente
                        String semestre = comboSemestre.getSelectedItem().toString();
                        String carrera = comboCarrera.getSelectedItem().toString();
                        String deporteSeleccionado = comboActividad1.getSelectedItem().toString();
                        String tallerCursoSeleccionado = comboActividad2.getSelectedItem().toString();
                        // Crear objeto SolicitudEstudiante
                        SolicitudEstudiante solicitud = new SolicitudEstudiante(nombre, matricula, semestre, carrera,
                                        deporteSeleccionado, tallerCursoSeleccionado);
                        // Enviar objeto al servidor
                        try (ObjectOutputStream objectOutput = new ObjectOutputStream(output)) {
                                objectOutput.writeObject(solicitud);
                                objectOutput.flush();
                        }
                        JOptionPane.showMessageDialog(this, "Datos enviados correctamente al servidor.", "Éxito",
                                        JOptionPane.INFORMATION_MESSAGE);
                        abrirConexionConElServidor();
                        iniciarEscuchaServidor();
                } catch (IOException | NullPointerException ex) {
                        ex.printStackTrace();
                        JOptionPane.showMessageDialog(this, "Error al enviar los datos al servidor.", "Error",
                                        JOptionPane.ERROR_MESSAGE);
                }
        }

        // <<--DE SERVIDOR A CLIENTE (INPUT)
        // Clase interna quie implementa un método para recibir objetos del servidor y
        // procesarlos
        private class EscucharServidor extends Thread {

                @Override
                public void run() {
                        try {
                                while (true) {
                                        String mensaje = input.readUTF();
                                        // Mostrar la información recibida en TextAreaInformacion1
                                        TextAreaInformacion1.append(mensaje);
                                }
                        } catch (IOException e) {
                                e.printStackTrace();
                        }
                }
        }

        private void iniciarEscuchaServidor() {
                EscucharServidor escucharServidor = new EscucharServidor();
                escucharServidor.start();
        }

