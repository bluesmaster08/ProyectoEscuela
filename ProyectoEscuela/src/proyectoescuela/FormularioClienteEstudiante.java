        // 4. Genera la información recibida del FormularioServidorEscuela en el
        // TextAreaInformacion en un archivo de texto.
        private void btnImprimirActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnImprimirActionPerformed
                // Obtener los datos del formulario
                String nombre = txtNombre.getText();
                String matricula = txtMatricula.getText();
                String semestre = comboSemestre.getSelectedItem().toString();
                String carrera = comboCarrera.getSelectedItem().toString();
                String actividad1 = comboActividad1.getSelectedItem().toString();
                String actividad2 = comboActividad2.getSelectedItem().toString();

                // Crear la cadena de la solicitud
                StringBuilder solicitud = new StringBuilder();
                solicitud.append(">>>>>>>>DATOS DE MI SOLICITUD>>>>>>>>>>>>>>>> ").append("\n");
                solicitud.append("Nombre: ").append(nombre).append("\n");
                solicitud.append("Matrícula: ").append(matricula).append("\n");
                solicitud.append("Semestre: ").append(semestre).append("\n");
                solicitud.append("Carrera: ").append(carrera).append("\n");
                solicitud.append("Actividad 1: ").append(actividad1).append("\n");
                solicitud.append("Actividad 2: ").append(actividad2).append("\n");
                solicitud.append("-----------------------------------------------------------------------")
                                .append("\n");

                // Imprimir la solicitud en TextAreaInformacion1
                TextAreaInformacion1.setText(solicitud.toString());
        }// GEN-LAST:event_btnImprimirActionPerformed

